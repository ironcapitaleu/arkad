/// The prefix of the path of a Notes fixture file in the manifest.
const NOTES_PREFIX: &str = "notes/";

/// The form of an annual report that the roll-up tests resolve.
const ANNUAL_FORM: &str = "10-K";

/// Returns one line per roll-up of [`SPIKE_ROLL_UPS`]: its name, then the confidence, the rule, and
/// the value of the fiscal year that ends at `year_end`, or `open`.
fn roll_up_lines(series: &Series, derived: &[StandardizedFact], year_end: Date) -> Vec<String> {
    SPIKE_ROLL_UPS
        .iter()
        .map(|concept| {
            fiscal_year_value(series.facts.iter().chain(derived), *concept, year_end).map_or_else(
                || format!("{}: open", concept.name()),
                |fact| {
                    format!(
                        "{}: {} {} {}",
                        concept.name(),
                        fact.confidence,
                        fact.rule,
                        fact.value
                    )
                },
            )
        })
        .collect()
}

/// Writes one test per fixture 10-K, and [`ROLL_UP_TESTED`], the list of their accessions. Each
/// test lists the roll-ups of the fiscal year of the 10-K.
macro_rules! roll_up_tests {
    ($($name:ident: $accession:literal => [$($line:literal,)+],)+) => {
        /// The accession of each fixture 10-K that a roll-up test resolves.
        const ROLL_UP_TESTED: &[&str] = &[$($accession),+];

        $(
            #[test]
            fn $name() {
                let resolved = resolve_fixture_filings(&[$accession]);
                let year_end = resolved.filings[0].period_of_report.expect(
                    "Given the sub row of a 10-K, the period of report should always exist",
                );
                let series = resolved.series();

                let expected_result = vec![$($line),+];

                let result = roll_up_lines(
                    &series,
                    &derived_values(&series),
                    year_end,
                );

                assert_eq!(result, expected_result);
            }
        )+
    };
}

