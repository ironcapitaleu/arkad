//! # Acceptance Test A1: Roll-Ups per 10-K
//!
//! Runs the rules of the standardized layer on each fixture 10-K alone: `core/dedup/more-precise@1`,
//! tiers 1 and 2 with [`UsGaap`], `core/dedup/newest-filing@1`, `core/period/q4-from-fy@1`, and the
//! derivation from a closed group. For the fiscal year of the 10-K, each test lists the 11 roll-ups
//! of the spike that map to a standard concept, with the confidence and the rule of the value, or
//! `open` if no rule gives one. A roll-up of the balance sheet is the value at the end of the fiscal
//! year. Any other roll-up is the value of the fiscal year.
//!
//! The tests show the gain of each rule: an alias or a derivation that lands changes a line from
//! `open` to its rule. The open lines of the 10-Ks of fiscal year 2013 come from five causes:
//!
//! - The filing reports the cash flow totals of continuing operations only, such as
//!   `NetCashProvidedByUsedInOperatingActivitiesContinuingOperations`.
//! - The filing reports a concept of the years before 2018, such as `SalesRevenueGoodsNet` or
//!   `CashAndCashEquivalentsPeriodIncreaseDecrease`.
//! - The filer is a bank, a utility, or an energy company, and reports its own revenue lines.
//! - The filing reports revenue with an extension concept of the filer.
//! - The filing reports no total, as KKR reports no revenue for 2013.
//!
//! ## External Dependencies
//!
//! None. The fixtures live in `src/tests/fixtures/data/`.

use chrono::NaiveDate;
use pretty_assertions::assert_eq;
use xbrl::core::closed_group::derive_from_closed_groups;
use xbrl::core::dedup::Series;
use xbrl::core::period_identity::derive_q4;
use xbrl::core::standardized::StandardizedFact;
use xbrl::tests::fixtures::data::resolved::{
    SPIKE_ROLL_UPS, fiscal_year_value, resolve_fixture_filings,
};

/// Returns one line per roll-up of [`SPIKE_ROLL_UPS`]: its name, then the confidence and the rule of
/// its value for the fiscal year that ends at `year_end`, or `open`.
fn roll_up_lines(
    series: &Series,
    derived: &[StandardizedFact],
    year_end: NaiveDate,
) -> Vec<String> {
    SPIKE_ROLL_UPS
        .iter()
        .map(|concept| {
            fiscal_year_value(series.facts.iter().chain(derived), *concept, year_end).map_or_else(
                || format!("{}: open", concept.name()),
                |fact| format!("{}: {} {}", concept.name(), fact.confidence, fact.rule),
            )
        })
        .collect()
}

/// Writes one test per fixture 10-K. Each lists the roll-ups of the fiscal year of the 10-K.
macro_rules! roll_up_tests {
    ($($name:ident: $accession:literal => [$($line:literal,)+],)+) => {
        $(
            #[test]
            fn $name() {
                let resolved = resolve_fixture_filings(&[$accession]);
                let year_end = resolved.filings[0].period_of_report.expect(
                    "Given the sub row of a 10-K, the period of report should always exist",
                );
                let series = resolved.series();
                let fourth_quarters = derive_q4(&series);

                let expected_result = vec![$($line),+];

                let result = roll_up_lines(
                    &series,
                    &derive_from_closed_groups(&series, &fourth_quarters),
                    year_end,
                );

                assert_eq!(result, expected_result);
            }
        )+
    };
}

